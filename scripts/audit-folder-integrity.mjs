#!/usr/bin/env node

import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT_JSON = 'audit/_meta/folder-integrity.json';
const OUTPUT_MD = 'audit/_meta/folder-integrity.md';
const GENERATED_OUTPUTS = new Set([OUTPUT_JSON, OUTPUT_MD]);

function git(args) {
  return execFileSync('git', args, {
    cwd: REPO_ROOT,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
    stdio: ['ignore', 'pipe', 'pipe'],
  });
}

function splitNull(value) {
  return value.split('\0').filter(Boolean);
}

function sha256(value) {
  return createHash('sha256').update(value).digest('hex');
}

function normalize(value) {
  return value.replaceAll('\\', '/').replace(/^\.\/+/, '');
}

function sourcePathForLegacyReport(reportPath) {
  if (!reportPath.startsWith('audit/') || !reportPath.endsWith('.txt')) return null;
  if (reportPath.startsWith('audit/_meta/')) return null;
  return reportPath.slice('audit/'.length, -'.txt'.length);
}

function extractReportedSha(text) {
  const patterns = [
    /\bSHA-?256\s*[:=]\s*([a-f0-9]{64})\b/i,
    /\bsha256\s*=\s*([a-f0-9]{64})\b/i,
  ];
  for (const pattern of patterns) {
    const match = text.match(pattern);
    if (match) return match[1].toLowerCase();
  }
  return null;
}

function summarize(items, key) {
  const counts = {};
  for (const item of items) counts[item[key]] = (counts[item[key]] ?? 0) + 1;
  return Object.fromEntries(Object.entries(counts).sort(([a], [b]) => a.localeCompare(b)));
}

function renderMarkdown(report) {
  const lines = [
    '# Audit folder integrity',
    '',
    `Schema: ${report.schemaVersion}`,
    `Source fingerprint: ${report.sourceFingerprint}`,
    `Tracked audit files: ${report.summary.trackedAuditFiles}`,
    `Current audited source files: ${report.summary.currentSourceFiles}`,
    `Legacy per-file reports: ${report.summary.legacyReports}`,
    `Historical meta reports: ${report.summary.historicalMetaReports}`,
    '',
    '## Integrity status',
    '',
    `- ignored files physically inside audit/: ${report.summary.ignoredAuditFiles}`,
    `- untracked files inside audit/: ${report.summary.untrackedAuditFiles}`,
    `- orphaned legacy reports: ${report.summary.orphanedLegacyReports}`,
    `- stale legacy reports with provable SHA drift: ${report.summary.staleLegacyReports}`,
    `- current legacy reports with matching SHA: ${report.summary.currentLegacyReports}`,
    `- unverifiable legacy reports without a source SHA: ${report.summary.unverifiableLegacyReports}`,
    `- current source files without a legacy report: ${report.summary.sourcesWithoutLegacyReport}`,
    '',
    '## Authority model',
    '',
    '- `audit/current/manifest.json` is the machine-readable authority for current source identity, classification, graph reachability, and risk-signal counts.',
    '- `audit/_meta/folder-integrity.json` is the machine-readable authority for the health of the complete audit folder.',
    '- Other `_meta` files and legacy `*.txt` per-file reports are historical evidence until regenerated by the current audit tooling.',
    '- A legacy report is marked stale only when it contains a parseable SHA-256 that differs from the current source. Reports without a parseable source SHA are explicitly unverifiable, not assumed current.',
    '',
  ];

  const sections = [
    ['Provably stale legacy reports', report.staleLegacyReports, (item) => `- \`${item.reportPath}\` → \`${item.sourcePath}\``],
    ['Orphaned legacy reports', report.orphanedLegacyReports, (item) => `- \`${item.reportPath}\` → missing \`${item.sourcePath}\``],
    ['Ignored files physically present', report.ignoredAuditFiles, (item) => `- \`${item}\``],
    ['Untracked files physically present', report.untrackedAuditFiles, (item) => `- \`${item}\``],
  ];
  for (const [heading, items, render] of sections) {
    lines.push(`## ${heading}`, '');
    if (items.length === 0) lines.push('- none');
    else for (const item of items) lines.push(render(item));
    lines.push('');
  }

  return `${lines.join('\n')}`;
}

export async function buildAuditFolderIntegrity() {
  const currentManifest = JSON.parse(
    await readFile(path.join(REPO_ROOT, 'audit/current/manifest.json'), 'utf8'),
  );
  const currentByPath = new Map(currentManifest.files.map((file) => [file.path, file]));
  const trackedAuditPaths = splitNull(git(['ls-files', '-z', 'audit']))
    .map(normalize)
    .filter((filePath) => !GENERATED_OUTPUTS.has(filePath))
    .sort();
  const ignoredAuditFiles = splitNull(
    git(['ls-files', '--others', '--ignored', '--exclude-standard', '-z', 'audit']),
  ).map(normalize).sort();
  const untrackedAuditFiles = splitNull(
    git(['ls-files', '--others', '--exclude-standard', '-z', 'audit']),
  ).map(normalize).sort();

  const legacyReports = [];
  const historicalMetaReports = [];
  for (const reportPath of trackedAuditPaths) {
    if (reportPath === 'audit/current/manifest.json' || reportPath === 'audit/current/README.md') {
      continue;
    }
    if (reportPath.startsWith('audit/_meta/')) {
      historicalMetaReports.push(reportPath);
      continue;
    }
    const sourcePath = sourcePathForLegacyReport(reportPath);
    if (!sourcePath) continue;
    const currentSource = currentByPath.get(sourcePath);
    if (!currentSource) {
      legacyReports.push({
        reportPath,
        sourcePath,
        status: 'orphaned',
        reportedSha256: null,
        currentSha256: null,
      });
      continue;
    }
    const text = await readFile(path.join(REPO_ROOT, reportPath), 'utf8');
    const reportedSha256 = extractReportedSha(text);
    const status = !reportedSha256
      ? 'unverifiable'
      : reportedSha256 === currentSource.sha256
        ? 'current'
        : 'stale';
    legacyReports.push({
      reportPath,
      sourcePath,
      status,
      reportedSha256,
      currentSha256: currentSource.sha256,
    });
  }

  legacyReports.sort((a, b) => a.reportPath.localeCompare(b.reportPath));
  historicalMetaReports.sort();
  const reportedSourcePaths = new Set(legacyReports.map((report) => report.sourcePath));
  const sourcesWithoutLegacyReport = currentManifest.files
    .map((file) => file.path)
    .filter((filePath) => !reportedSourcePaths.has(filePath))
    .sort();
  const staleLegacyReports = legacyReports.filter((report) => report.status === 'stale');
  const orphanedLegacyReports = legacyReports.filter((report) => report.status === 'orphaned');
  const statusCounts = summarize(legacyReports, 'status');

  const sourceFingerprint = sha256(
    Buffer.from([
      currentManifest.repository.worktreeFingerprint,
      ...trackedAuditPaths,
      ...ignoredAuditFiles.map((filePath) => `ignored:${filePath}`),
      ...untrackedAuditFiles.map((filePath) => `untracked:${filePath}`),
    ].join('\n')),
  );

  const report = {
    schemaVersion: 1,
    sourceFingerprint,
    authority: {
      currentSourceManifest: 'audit/current/manifest.json',
      folderIntegrityReport: OUTPUT_JSON,
      historicalReportPolicy:
        'All other audit reports are historical evidence unless their current source SHA is verified.',
    },
    summary: {
      trackedAuditFiles: trackedAuditPaths.length + GENERATED_OUTPUTS.size,
      currentSourceFiles: currentManifest.files.length,
      legacyReports: legacyReports.length,
      historicalMetaReports: historicalMetaReports.length,
      ignoredAuditFiles: ignoredAuditFiles.length,
      untrackedAuditFiles: untrackedAuditFiles.length,
      orphanedLegacyReports: statusCounts.orphaned ?? 0,
      staleLegacyReports: statusCounts.stale ?? 0,
      currentLegacyReports: statusCounts.current ?? 0,
      unverifiableLegacyReports: statusCounts.unverifiable ?? 0,
      sourcesWithoutLegacyReport: sourcesWithoutLegacyReport.length,
    },
    ignoredAuditFiles,
    untrackedAuditFiles,
    historicalMetaReports,
    staleLegacyReports,
    orphanedLegacyReports,
    sourcesWithoutLegacyReport,
    legacyReports,
  };

  return {
    report,
    outputs: new Map([
      [OUTPUT_JSON, `${JSON.stringify(report, null, 2)}\n`],
      [OUTPUT_MD, renderMarkdown(report)],
    ]),
  };
}

async function main() {
  const verify = process.argv.includes('--verify');
  const { report, outputs } = await buildAuditFolderIntegrity();
  const failures = [];
  for (const [filePath, expected] of outputs) {
    const absolutePath = path.join(REPO_ROOT, filePath);
    if (verify) {
      let actual = null;
      try {
        actual = await readFile(absolutePath, 'utf8');
      } catch (error) {
        if (error?.code !== 'ENOENT') throw error;
      }
      if (actual !== expected) failures.push(`${filePath}: missing or stale`);
    } else {
      await writeFile(absolutePath, expected, 'utf8');
    }
  }

  if (verify) {
    if (report.ignoredAuditFiles.length) failures.push('ignored files exist inside audit/');
    if (report.untrackedAuditFiles.length) failures.push('untracked files exist inside audit/');
    if (failures.length) {
      process.stderr.write(`Audit folder integrity failed:\n${failures.map((item) => `- ${item}`).join('\n')}\n`);
      process.exitCode = 1;
      return;
    }
    process.stdout.write(`Audit folder integrity verified (${report.sourceFingerprint}).\n`);
  } else {
    process.stdout.write(`Generated full-folder audit integrity for ${report.summary.trackedAuditFiles} tracked audit files.\n`);
  }
}

main().catch((error) => {
  process.stderr.write(`${error.stack ?? error.message}\n`);
  process.exitCode = 1;
});
